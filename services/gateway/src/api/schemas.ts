import { Type, type Static, type TSchema } from "typebox";

const UUID_V4 =
  "^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$";

const ERROR_CODES = [
  "BAD_REQUEST",
  "UNAUTHORIZED",
  "FORBIDDEN",
  "NOT_FOUND",
  "PAYLOAD_TOO_LARGE",
  "UNSUPPORTED_MEDIA_TYPE",
  "RATE_LIMITED",
  "INTERNAL_ERROR",
  "UPSTREAM_UNAVAILABLE",
  "SERVICE_UNAVAILABLE",
  "UPSTREAM_TIMEOUT",
] as const;

export const ErrorCode = Type.Enum([...ERROR_CODES], {
  description: "Stable, machine-readable error code",
});
export type ErrorCode = Static<typeof ErrorCode>;

export const StorageErrorCode = Type.Enum(
  [...ERROR_CODES, "SECRETS_SEALED", "STORAGE_QUOTA_EXCEEDED"],
  { description: "Stable, machine-readable error code" },
);

export const SecretsErrorCode = Type.Enum([...ERROR_CODES, "SECRETS_SEALED"], {
  description: "Stable, machine-readable error code",
});
export type SecretsErrorCode = Static<typeof SecretsErrorCode>;

function errorBody<T extends TSchema>(code: T) {
  return Type.Object(
    {
      error: Type.Object(
        {
          code,
          message: Type.String({ description: "Human-readable explanation" }),
          requestId: Type.String({
            format: "uuid",
            description:
              "Same as the X-Request-Id header. Quote it when reporting a problem.",
          }),
        },
        { additionalProperties: false },
      ),
    },
    { additionalProperties: false },
  );
}

export const ErrorResponse = errorBody(ErrorCode);
export type ErrorResponse = Static<typeof ErrorResponse>;
export const SecretsErrorResponse = errorBody(SecretsErrorCode);
export const StorageErrorResponse = errorBody(StorageErrorCode);
const SealedErrorResponse = errorBody(
  Type.Enum([...ERROR_CODES, "SECRETS_SEALED"], {
    description: "Stable, machine-readable error code",
  }),
);
const QuotaErrorResponse = errorBody(
  Type.Enum([...ERROR_CODES, "STORAGE_QUOTA_EXCEEDED"], {
    description: "Stable, machine-readable error code",
  }),
);

export const FileId = Type.String({
  pattern: UUID_V4,
  description: "File ID returned by the upload (a lowercase version 4 UUID)",
  example: "3f2c9b1e-6a4d-4c8e-9f1a-2b3c4d5e6f70",
});

export const FileParams = Type.Object({ id: FileId });
export type FileParams = Static<typeof FileParams>;

export const FileMetadata = Type.Object(
  {
    id: FileId,
    size: Type.Integer({
      minimum: 0,
      description: "Number of bytes stored (the original, unencrypted size)",
      example: 48213,
    }),
    name: Type.String({
      nullable: true,
      description: "The original filename, if one was given (X-File-Name)",
      example: "invoice-2026-11.pdf",
    }),
    contentType: Type.String({
      description:
        "The upload's Content-Type (downloads are always sent as application/octet-stream)",
      example: "application/pdf",
    }),
    createdAt: Type.String({
      format: "date-time",
      example: "2026-11-05T09:30:00.000Z",
    }),
  },
  { additionalProperties: false },
);
export const UploadResponse = FileMetadata;
export type UploadResponse = Static<typeof UploadResponse>;

export const HealthResponse = Type.Object(
  { status: Type.Enum(["ok"]) },
  { additionalProperties: false },
);

export const ReadinessResponse = Type.Object(
  {
    status: Type.Enum(["ready", "degraded", "not_ready"], {
      description:
        "ready: all dependencies up. degraded: rate limiting unavailable, API still served. not_ready: can't serve requests.",
    }),
    checks: Type.Object(
      {
        postgres: Type.Enum(["up", "down"]),
        redis: Type.Enum(["up", "down"]),
      },
      { additionalProperties: false },
    ),
  },
  { additionalProperties: false },
);

export const UploadHeaders = Type.Object({
  "content-type": Type.Optional(
    Type.String({
      description: "Any type is accepted; the file is stored as raw bytes",
      example: "application/octet-stream",
    }),
  ),
  "x-file-name": Type.Optional(
    Type.String({
      maxLength: 1024,
      description:
        "The original filename, percent-encoded UTF-8 allowed (1-255 characters, no slashes or control characters). Kept in the metadata only; never used on disk.",
      example: "invoice%202026-11.pdf",
    }),
  ),
});

export const requestIdHeader = {
  "X-Request-Id": Type.String({
    format: "uuid",
    description: "Unique ID of this request, generated by the gateway",
  }),
};

export const rateLimitHeaders = {
  ...requestIdHeader,
  "RateLimit-Limit": Type.Integer({
    description: "Requests allowed per window for this API key",
  }),
  "RateLimit-Remaining": Type.Integer({
    description: "Requests left in the current window",
  }),
  "RateLimit-Reset": Type.Integer({
    description: "Seconds until the window resets",
  }),
};

export function requiredHeader<T extends object>(
  schema: T,
): T & { "x-required": true } {
  return { ...schema, "x-required": true };
}

export function errorResponse(
  description: string,
  code: string,
  message: string,
  schema: object = ErrorResponse,
) {
  return {
    description,
    headers: requestIdHeader,
    content: {
      "application/json": {
        schema,
        example: {
          error: {
            code,
            message,
            requestId: "3f2c9b1e-6a4d-4c8e-9f1a-2b3c4d5e6f70",
          },
        },
      },
    },
  };
}

export function commonErrors(service: {
  name: string;
  label: string;
  schema?: object;
}) {
  const error = (
    description: string,
    code: SecretsErrorCode,
    message: string,
  ) => errorResponse(description, code, message, service.schema);
  return {
    401: error(
      "UNAUTHORIZED: the API key is missing, wrong or revoked (always the same answer).",
      "UNAUTHORIZED",
      "A valid API key is required",
    ),
    403: error(
      "FORBIDDEN: the key's tenant is suspended.",
      "FORBIDDEN",
      "This tenant is suspended",
    ),
    429: {
      ...error(
        "RATE_LIMITED: too many requests for this key, or too many failed attempts from this IP. Retry after `Retry-After` seconds.",
        "RATE_LIMITED",
        "Too many requests, try again later",
      ),
      headers: {
        ...rateLimitHeaders,
        "Retry-After": Type.Integer({
          description: "Seconds to wait before retrying",
        }),
      },
    },
    500: error(
      "INTERNAL_ERROR: something went wrong on our side.",
      "INTERNAL_ERROR",
      "Something went wrong",
    ),
    502: error(
      `UPSTREAM_UNAVAILABLE: ${service.name} can't be reached.`,
      "UPSTREAM_UNAVAILABLE",
      `${service.label} is unavailable`,
    ),
    503: error(
      "SERVICE_UNAVAILABLE: temporarily unavailable (for example during a restart). Retry later.",
      "SERVICE_UNAVAILABLE",
      "Service temporarily unavailable, try again later",
    ),
    504: error(
      `UPSTREAM_TIMEOUT: ${service.name} didn't answer in time.`,
      "UPSTREAM_TIMEOUT",
      `${service.label} did not respond in time`,
    ),
  };
}

const storageErrors = commonErrors({
  name: "file storage",
  label: "Storage service",
});

export const security = [{ apiKey: [] }];

const fileExample = {
  id: "3f2c9b1e-6a4d-4c8e-9f1a-2b3c4d5e6f70",
  size: 48213,
  name: "invoice-2026-11.pdf",
  contentType: "application/pdf",
  createdAt: "2026-11-05T09:30:00.000Z",
};

const sealedOrUnavailable = errorResponse(
  "SECRETS_SEALED: the secrets service is sealed (e.g. after a restart), so files can't be encrypted or decrypted until an operator unseals it; retry later. SERVICE_UNAVAILABLE: temporarily unavailable.",
  "SECRETS_SEALED",
  "The secrets service is sealed, so files can't be encrypted or decrypted",
  SealedErrorResponse,
);

const fileNotFound = errorResponse(
  'NOT_FOUND: no such file for this tenant (another tenant\'s file is also "not found").',
  "NOT_FOUND",
  "File not found",
);

const newFileRouteErrors = commonErrors({
  name: "file storage",
  label: "Storage service",
  schema: StorageErrorResponse,
});

export const uploadFileSchema = {
  operationId: "uploadFile",
  tags: ["Files"],
  summary: "Upload a file",
  description:
    "Send the file as the raw request body (and optionally its name in X-File-Name). It is encrypted as it streams in, before it reaches the disk, and gets a new ID. The maximum size depends on the deployment (1 GiB by default), and counts against your storage limit.",
  security,
  headers: UploadHeaders,
  body: {
    content: {
      "application/octet-stream": { schema: Type.String({ format: "binary" }) },
    },
  },
  response: {
    201: {
      description: "Stored",
      headers: rateLimitHeaders,
      content: {
        "application/json": {
          schema: UploadResponse,
          example: fileExample,
        },
      },
    },
    ...storageErrors,
    413: errorResponse(
      "PAYLOAD_TOO_LARGE: the file is larger than the allowed maximum. STORAGE_QUOTA_EXCEEDED: it would go over your storage limit (see GET /v1/storage/usage).",
      "PAYLOAD_TOO_LARGE",
      "The upload is larger than the allowed maximum",
      QuotaErrorResponse,
    ),
    503: sealedOrUnavailable,
  },
};

export const downloadFileSchema = {
  operationId: "downloadFile",
  tags: ["Files"],
  summary: "Download a file",
  description:
    "Returns the file's bytes exactly as uploaded. Only the tenant that uploaded a file can download it.",
  security,
  params: FileParams,
  response: {
    200: {
      description:
        "The file's bytes, decrypted chunk by chunk. If a chunk fails its integrity check part-way, the connection is cut, so a partial file is never mistaken for a complete one.",
      headers: {
        ...rateLimitHeaders,
        "Content-Length": Type.Integer({ description: "File size in bytes" }),
        "Content-Disposition": Type.String({
          description:
            'Always `attachment`, with the original name (`filename="..."` and an encoded `filename*=`), so browsers save the file instead of showing it.',
        }),
        "X-Content-Type-Options": Type.String({
          enum: ["nosniff"],
          description:
            "Browsers must not guess the type (uploaded HTML can't run).",
        }),
      },
      content: {
        "application/octet-stream": {
          schema: Type.String({ format: "binary" }),
        },
      },
    },
    400: errorResponse(
      "BAD_REQUEST: the file ID isn't a valid ID.",
      "BAD_REQUEST",
      "params/id must match pattern",
    ),
    ...storageErrors,
    404: fileNotFound,
    503: sealedOrUnavailable,
  },
};

const badFileId = errorResponse(
  "BAD_REQUEST: the file ID isn't a valid ID, or a query parameter is invalid.",
  "BAD_REQUEST",
  "params/id must match pattern",
  StorageErrorResponse,
);

