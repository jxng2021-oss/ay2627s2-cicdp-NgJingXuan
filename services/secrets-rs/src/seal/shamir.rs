#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ShamirError(pub &'static str);

impl std::fmt::Display for ShamirError {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter.write_str(self.0)
    }
}

impl std::error::Error for ShamirError {}

fn add(a: u8, b: u8) -> u8 {
    a ^ b
}

fn div(a: u8, b: u8) -> Result<u8, ShamirError> {
    if b == 0 {
        return Err(ShamirError("cannot divide by zero"));
    }
    let log_a = usize::from(LOG_TABLE[usize::from(a)]);
    let log_b = usize::from(LOG_TABLE[usize::from(b)]);
    let diff = (log_a + 255 - log_b) % 255;
    let result = EXP_TABLE[diff];
    Ok(if a == 0 { 0 } else { result })
}

fn mult(a: u8, b: u8) -> u8 {
    let log_a = usize::from(LOG_TABLE[usize::from(a)]);
    let log_b = usize::from(LOG_TABLE[usize::from(b)]);
    let sum = (log_a + log_b) % 255;
    let result = EXP_TABLE[sum];
    if a == 0 || b == 0 { 0 } else { result }
}

fn interpolate_polynomial(x_samples: &[u8], y_samples: &[u8], x: u8) -> Result<u8, ShamirError> {
    if x_samples.len() != y_samples.len() {
        return Err(ShamirError("sample length mistmatch"));
    }
    let limit = x_samples.len();
    let mut result = 0;
    for i in 0..limit {
        let mut basis = 1;
        for j in 0..limit {
            if i == j {
                continue;
            }
            let num = add(x, x_samples[j]);
            let denom = add(x_samples[i], x_samples[j]);
            let term = div(num, denom)?;
            basis = mult(basis, term);
        }
        result = add(result, mult(y_samples[i], basis));
    }
    Ok(result)
}

fn evaluate(coefficients: &[u8], x: u8, degree: usize) -> Result<u8, ShamirError> {
    if x == 0 {
        return Err(ShamirError("cannot evaluate secret polynomial at zero"));
    }
    let mut result = coefficients[degree];
    for i in (0..degree).rev() {
        result = add(mult(result, x), coefficients[i]);
    }
    Ok(result)
}

fn random_bytes(count: usize) -> Zeroizing<Vec<u8>> {
    let mut bytes = Zeroizing::new(vec![0u8; count]);
    rand::RngCore::fill_bytes(&mut rand::rngs::OsRng, &mut bytes);
    bytes
}

fn new_coefficients(intercept: u8, degree: usize) -> Zeroizing<Vec<u8>> {
    let mut coefficients = Zeroizing::new(vec![0u8; degree + 1]);
    coefficients[0] = intercept;
    coefficients[1..].copy_from_slice(&random_bytes(degree));
    coefficients
}

fn new_coordinates() -> [u8; 255] {
    let mut coordinates = [0u8; 255];
    for (index, coordinate) in coordinates.iter_mut().enumerate() {
        *coordinate = u8::try_from(index + 1).unwrap_or(255);
    }
    let random_indices = random_bytes(255);
    for i in 0..255 {
        let j = usize::from(random_indices[i]) % 255;
        coordinates.swap(i, j);
    }
    coordinates
}

pub fn split(
    secret: &[u8],
    shares: usize,
    threshold: usize,
) -> Result<Vec<Zeroizing<Vec<u8>>>, ShamirError> {
    if secret.is_empty() {
        return Err(ShamirError("secret cannot be empty"));
    }
    if !(2..256).contains(&shares) {
        return Err(ShamirError("shares must be at least 2 and at most 255"));
    }
    if !(2..256).contains(&threshold) {
        return Err(ShamirError("threshold must be at least 2 and at most 255"));
    }
    if shares < threshold {
        return Err(ShamirError("shares cannot be less than threshold"));
    }

    let secret_length = secret.len();
    let mut x_coordinates = new_coordinates();
    let mut result: Vec<Zeroizing<Vec<u8>>> = (0..shares)
        .map(|i| {
            let mut share = Zeroizing::new(vec![0u8; secret_length + 1]);
            share[secret_length] = x_coordinates[i];
            share
        })
        .collect();

    let degree = threshold - 1;
    for (i, byte) in secret.iter().enumerate() {
        let coefficients = new_coefficients(*byte, degree);
        for (j, share) in result.iter_mut().enumerate() {
            share[i] = evaluate(&coefficients, x_coordinates[j], degree)?;
        }
    }
    x_coordinates.zeroize();
    Ok(result)
}

pub fn combine(shares: &[&[u8]]) -> Result<Zeroizing<Vec<u8>>, ShamirError> {
    if !(2..256).contains(&shares.len()) {
        return Err(ShamirError(
            "shares must have at least 2 and at most 255 elements",
        ));
    }
    let share_length = shares[0].len();
    for share in shares {
        if share.len() < 2 {
            return Err(ShamirError("each share must be at least 2 bytes"));
        }
        if share.len() != share_length {
            return Err(ShamirError("all shares must have the same byte length"));
        }
    }

    let secret_length = share_length - 1;
    let mut secret = Zeroizing::new(vec![0u8; secret_length]);
    let mut x_samples = Zeroizing::new(vec![0u8; shares.len()]);
    let mut y_samples = Zeroizing::new(vec![0u8; shares.len()]);

    let mut samples = HashSet::new();
    for (i, share) in shares.iter().enumerate() {
        let sample = share[share_length - 1];
        if !samples.insert(sample) {
            return Err(ShamirError(
                "shares must contain unique values but a duplicate was found",
            ));
        }
        x_samples[i] = sample;
    }

    for (i, byte) in secret.iter_mut().enumerate() {
        for (j, share) in shares.iter().enumerate() {
            y_samples[j] = share[i];
        }
        *byte = interpolate_polynomial(&x_samples, &y_samples, 0)?;
    }
    Ok(secret)
}
